use std::{path::PathBuf, sync::OnceLock};

use cow_utils::CowUtils;
use robusta_linter::table::RuleTableRow;
use schemars::schema::Schema;

use website_common::Renderer;

pub(super) fn render_rule_docs_page(rule: &RuleTableRow, renderer: &Renderer) -> String {
    let name = rule.name;
    let category = rule.category;
    let default = rule.turned_on_by_default;
    let fix = rule.autofix.as_str();
    let source = rule_source(rule);
    let documentation = rule.documentation.unwrap_or_default();
    let configuration = if let Some(Schema::Object(schema)) = &rule.settings_schema {
        let section = renderer.render_schema(2, "", schema);
        let settings = section.to_md(renderer);
        if settings.trim().is_empty() {
            String::new()
        } else {
            format!("## Configuration\n{settings}\n")
        }
    } else {
        String::new()
    };

    let file = file!();
    #[cfg(windows)]
    #[expect(clippy::disallowed_methods, reason = "file path always contains slashes")]
    let file = &*file.replace('\\', "/");

    format!(
        "---\ntitle: \"{name}\"\nrule: \"{name}\"\ncategory: \"{category}\"\ndefault: {default}\nfix: \"{fix}\"\nsource: \"{source}\"\n---\n\n\
         <!-- This file is auto-generated by {file}. Do not edit it manually. -->\n\n\
         <RuleHeader />\n\n{documentation}\n{configuration}\
         ## How to use\n<RuleHowToUse />\n\n\
         ## References\n<RuleReferences />\n"
    )
}

/// The rule's source file, relative to the repository root.
fn rule_source(rule: &RuleTableRow) -> String {
    const LINT_RULES_DIR: &str = "crates/robusta_linter/src/rules";
    static ROOT: OnceLock<PathBuf> = OnceLock::new();
    let root =
        ROOT.get_or_init(|| project_root::get_project_root().expect("project root should exist"));

    // Some rules are folders with a mod.rs file, others are just a rust file
    let rule_name = rule.name.cow_replace('-', "_");
    if root.join(LINT_RULES_DIR).join(&*rule_name).is_dir() {
        format!("{LINT_RULES_DIR}/{rule_name}/mod.rs")
    } else {
        format!("{LINT_RULES_DIR}/{rule_name}.rs")
    }
}
